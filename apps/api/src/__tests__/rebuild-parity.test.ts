/**
 * Plan 4 (2026-11-23): the read model a rebuild gives is the one the live
 * projection wrote.
 *
 * scripts/reproject.ts is the way back from a broken read model, and it
 * had never been run against the projection it replaces: a projector that
 * reads something besides the event (the wall clock, another table, the
 * row as it was) would rebuild a different read model, found out only on
 * the day it was needed.
 *
 * One organisation's history (an order attached to a run, a purchase with
 * a per-store price, a line marked unavailable, an expense added and one
 * removed, delivery, a short line, finish) is projected live, its read
 * model rows are kept, deleted, and rebuilt with the script's own replay
 * (services/replay.ts) for that organisation only. The rows must match,
 * but for `updated_at`, which the run projector takes from the clock, and
 * price_history's `created_at`, the row's insert time.
 *
 * PG-gated.
 */
import { describe, expect, test } from 'bun:test';
import { randomUUID } from 'node:crypto';
import { sql } from 'drizzle-orm';
import { getDb, schema as s, type DB } from '@compass/db';
import { applyRun, emptyRunState, type ActorCtx, type RunEvent } from '@compass/domain/run';
import {
  apply as applyOrder,
  emptyState as emptyOrderState,
  type OrderEvent,
} from '@compass/domain/order';
import { projectOrder } from '@compass/streams';
import { projectRun } from '../services/runProjection';
import { replay } from '../services/replay';
import { SHOULD_RUN } from './helpers/pg';
import { seedOwnedOrg } from './helpers/fixtures';
import { runStream, seedOrder } from './helpers/streams';
import { cleanUpAfterAll } from './helpers/cleanup';

cleanUpAfterAll();

/** Rows of a read-model table for one organisation, without the clock's columns, in a fixed order. */
const TABLES: ReadonlyArray<{ name: string; where: string; order: string; clock?: string }> = [
  { name: 'read_model.market_runs_v', where: 'org_id = $org', order: 'id' },
  {
    name: 'read_model.run_items_v',
    where: 'run_id IN (SELECT id FROM read_model.market_runs_v WHERE org_id = $org)',
    order: 'run_id, sku_id',
  },
  {
    name: 'read_model.run_item_stores_v',
    where: 'run_id IN (SELECT id FROM read_model.market_runs_v WHERE org_id = $org)',
    order: 'run_id, sku_id, store_id',
  },
  { name: 'read_model.run_expenses_v', where: 'org_id = $org', order: 'id' },
  { name: 'read_model.order_sessions_v', where: 'org_id = $org', order: 'id' },
  {
    name: 'read_model.order_items_v',
    where: 'session_id IN (SELECT id FROM read_model.order_sessions_v WHERE org_id = $org)',
    order: 'session_id, sku_id',
  },
  {
    name: 'inventory.price_history',
    where: 'org_id = $org',
    order: 'run_id, sku_id, store_id',
    // The row's insert time (a column default); observed_at is the event's.
    clock: 'created_at',
  },
];

async function readModelOf(db: DB, orgId: string): Promise<Record<string, unknown[]>> {
  const out: Record<string, unknown[]> = {};
  for (const t of TABLES) {
    const where = t.where.replaceAll('$org', `'${orgId}'::uuid`);
    const rows = (await db.execute(
      sql.raw(`SELECT to_jsonb(x) - 'updated_at' - 'id' - '${t.clock ?? 'updated_at'}' AS row FROM ${t.name} x
               WHERE ${where} ORDER BY ${t.order}, to_jsonb(x)::text`),
    )) as unknown as Array<{ row: Record<string, unknown> }>;
    // price_history and run_items_v ids are generated by the projector;
    // run, session and expense ids come from the events and are checked
    // through the columns that point at them.
    out[t.name] = rows.map((r) => r.row);
  }
  return out;
}

describe.skipIf(!SHOULD_RUN)('a rebuild from the log (PG)', () => {
  test("gives the read model the live projection wrote, for one organisation's history", async () => {
    const db = getDb(undefined, { system: 'maintenance' });
    const { orgId, slug, session } = await seedOwnedOrg(db, 'Rebuild Parity');
    const actor: ActorCtx = {
      userId: session.userId,
      memberId: session.memberId,
      permissions: session.permissions,
    };
    const [storeA] = await db
      .insert(s.stores)
      .values({ orgId, name: 'A', code: `A-${slug.slice(-6)}` })
      .returning();
    const [storeB] = await db
      .insert(s.stores)
      .values({ orgId, name: 'B', code: `B-${slug.slice(-6)}` })
      .returning();
    const [apple, pear] = await db
      .insert(s.skus)
      .values([
        { orgId, code: `APL-${slug.slice(-6)}`, names: { en: 'Apple' }, unit: 'kg', step: '0.5' },
        { orgId, code: `PER-${slug.slice(-6)}`, names: { en: 'Pear' }, unit: 'kg', step: '0.5' },
      ])
      .returning();
    if (!storeA || !storeB || !apple || !pear) throw new Error('fixture insert failed');

    const runId = randomUUID();
    const author = { ...actor, isClaimer: false };
    const sessionA = await seedOrder(orgId, author, {
      storeId: storeA.id,
      items: [
        { skuId: apple.id, qty: '2' },
        { skuId: pear.id, qty: '1' },
      ],
      until: { runId },
    });
    const sessionB = await seedOrder(orgId, author, {
      storeId: storeB.id,
      items: [{ skuId: apple.id, qty: '2' }],
      extras: 1,
      until: { runId },
    });

    const run = runStream(orgId, runId);
    await run.exec({
      type: 'PlanRun',
      orgId,
      runDate: '2026-10-20',
      today: '2026-10-20',
      runIndex: 0,
      sessionIds: [sessionA, sessionB],
      plannedItems: [
        { skuId: apple.id, qty: '4' },
        { skuId: pear.id, qty: '1' },
      ],
      actor,
    });
    await run.exec({ type: 'StartPurchase', actor });
    await run.exec({
      type: 'PurchaseItem',
      skuId: apple.id,
      supplierId: null,
      unitPrice: '12000',
      actualQty: '4',
      receiptPhotoUrl: null,
      storeSplits: [
        { storeId: storeA.id, qty: '2' },
        { storeId: storeB.id, qty: '2', unitPrice: '15000', paymentMethod: 'transfer' },
      ],
      paymentMethod: 'cash',
      actor,
    });
    await run.exec({ type: 'MarkUnavailable', skuId: pear.id, note: 'sold out', actor });
    const kept = randomUUID();
    const removed = randomUUID();
    for (const expenseId of [kept, removed]) {
      await run.exec({
        type: 'AddRunExpense',
        expenseId,
        label: 'porter',
        qty: '1',
        unitPrice: '5000',
        storeSplits: [
          { storeId: storeA.id, qty: '0.5' },
          { storeId: storeB.id, qty: '0.5' },
        ],
        paymentMethod: 'cash',
        receiptPhotoUrl: null,
        reason: 'carry',
        actor,
      });
    }
    await run.exec({ type: 'RemoveRunExpense', expenseId: removed, reason: 'twice', actor });
    await run.exec({ type: 'StartDelivery', actor });
    for (const storeId of [storeA.id, storeB.id]) {
      await run.exec({ type: 'DeliverToStore', storeId, actor });
    }
    await run.exec({
      type: 'ConfirmStoreItem',
      storeId: storeA.id,
      skuId: apple.id,
      status: 'short',
      note: 'half a kilo missing',
      photoUrl: null,
      receivedQty: '1.5',
      actor,
    });
    await run.exec({
      type: 'ConfirmStoreItem',
      storeId: storeB.id,
      skuId: apple.id,
      status: 'ok',
      note: null,
      photoUrl: null,
      actor,
    });
    for (const storeId of [storeA.id, storeB.id]) {
      await run.exec({ type: 'ConfirmStore', storeId, actor });
    }
    await run.exec({ type: 'FinishRun', actor });

    const live = await readModelOf(db, orgId);
    // The history reached every table this test compares.
    for (const t of TABLES) expect(live[t.name]!.length).toBeGreaterThan(0);

    await db.transaction(async (tx) => {
      // Cascades to run_items_v, run_item_stores_v, run_expenses_v, order_items_v.
      await tx.execute(sql`DELETE FROM read_model.market_runs_v WHERE org_id = ${orgId}`);
      await tx.execute(sql`DELETE FROM read_model.order_sessions_v WHERE org_id = ${orgId}`);
      await tx.execute(sql`DELETE FROM inventory.price_history WHERE org_id = ${orgId}`);
      await replay<RunEvent, ReturnType<typeof emptyRunState>>(tx, {
        streamType: 'run',
        empty: emptyRunState,
        apply: applyRun,
        project: projectRun,
        orgId,
      });
      await replay<OrderEvent, ReturnType<typeof emptyOrderState>>(tx, {
        streamType: 'order',
        empty: emptyOrderState,
        apply: applyOrder,
        project: projectOrder,
        orgId,
      });
    });

    expect(await readModelOf(db, orgId)).toEqual(live);
  });
});
